import React, { useState, useEffect } from 'react';
import { useParams, Link } from 'react-router-dom';
import { api } from '../../api/client.js';
import {
  HeartPulse,
  AlertTriangle,
  Shield,
  Phone,
} from 'lucide-react';

export const PublicEmergencyView: React.FC = () => {
  const { token } = useParams<{ token: string }>();
  const [data, setData] = useState<any>(null);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const fetchEmergencyData = async () => {
      try {
        setLoading(true);
        const res = await api.get(`/emergency/public/${token}`);
        setData(res.data.data);
      } catch (err: any) {
        setError(err?.response?.data?.message || 'Invalid or revoked emergency access token.');
      } finally {
        setLoading(false);
      }
    };

    if (token) {
      fetchEmergencyData();
    }
  }, [token]);

  if (loading) {
    return (
      <div className="min-h-screen bg-navy-950 flex items-center justify-center p-4">
        <div className="text-center space-y-3">
          <HeartPulse className="w-10 h-10 text-red-500 animate-pulse mx-auto" />
          <p className="text-slate-400 text-sm">Accessing emergency medical vault...</p>
        </div>
      </div>
    );
  }

  if (error || !data) {
    return (
      <div className="min-h-screen bg-navy-950 flex items-center justify-center p-4">
        <div className="bg-navy-900 border border-red-500/30 rounded-3xl p-8 max-w-md w-full text-center space-y-4">
          <AlertTriangle className="w-12 h-12 text-red-400 mx-auto" />
          <h1 className="text-lg font-bold text-white">Emergency Token Inactive</h1>
          <p className="text-xs text-slate-400">{error || 'Token not found.'}</p>
          <Link
            to="/login"
            className="inline-block mt-4 px-4 py-2 bg-slate-800 text-slate-200 rounded-xl text-xs font-semibold"
          >
            Return to MediChain Login
          </Link>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-navy-950 p-4 md:p-8 flex flex-col items-center justify-center">
      <div className="max-w-xl w-full space-y-6">
        {/* First Responder Banner */}
        <div className="p-4 bg-red-950/40 border border-red-500/40 rounded-2xl flex items-start gap-3 text-xs text-red-200">
          <AlertTriangle className="w-5 h-5 text-red-400 shrink-0 mt-0.5" />
          <div>
            <p className="font-bold text-red-300">First Responder Emergency Access</p>
            <p className="text-red-200/90 mt-0.5">
              This token was generated by the patient for emergency triage. Full health records and
              AES-256 encrypted documents remain restricted.
            </p>
          </div>
        </div>

        {/* Card */}
        <div className="bg-gradient-to-br from-navy-900 via-navy-850 to-teal-950 border border-red-500/30 rounded-3xl p-6 shadow-2xl space-y-6">
          <div className="flex items-center justify-between border-b border-slate-800 pb-4">
            <div className="flex items-center gap-2.5">
              <div className="p-2 bg-red-500/20 text-red-400 rounded-xl">
                <HeartPulse className="w-6 h-6" />
              </div>
              <div>
                <h1 className="font-bold text-lg text-white">Triage Emergency ID</h1>
                <p className="text-[10px] text-teal-300 font-mono">MediChain-AI Safe View</p>
              </div>
            </div>
            <span className="px-2.5 py-1 bg-red-500/20 text-red-300 border border-red-500/30 rounded-full text-[10px] font-bold uppercase tracking-wider">
              Emergency Mode
            </span>
          </div>

          <div className="space-y-4">
            <div>
              <span className="text-[10px] text-slate-400 uppercase tracking-wider block">Patient Name</span>
              <p className="text-xl font-bold text-white">{data.patientName || 'Anonymous Patient'}</p>
            </div>

            <div className="grid grid-cols-2 gap-4 pt-3 border-t border-slate-800 text-xs">
              <div className="p-3 bg-navy-950/80 rounded-xl border border-slate-800">
                <span className="text-slate-400 block text-[10px] uppercase">Blood Group</span>
                <span className="text-2xl font-black text-rose-400">{data.bloodGroup || 'UNKNOWN'}</span>
              </div>
              <div className="p-3 bg-navy-950/80 rounded-xl border border-slate-800">
                <span className="text-slate-400 block text-[10px] uppercase">Allergies</span>
                <span className="text-xs font-semibold text-amber-300 mt-1 block">
                  {data.allergies && data.allergies.length > 0
                    ? data.allergies.join(', ')
                    : 'No allergies listed'}
                </span>
              </div>
            </div>

            {data.conditionsSummary && (
              <div className="p-3 bg-navy-950/80 rounded-xl border border-slate-800 text-xs">
                <span className="text-slate-400 block text-[10px] uppercase mb-1">
                  Conditions / Medical Alerts
                </span>
                <p className="text-slate-200 leading-relaxed">{data.conditionsSummary}</p>
              </div>
            )}

            {data.emergencyContacts && data.emergencyContacts.length > 0 && (
              <div className="p-3 bg-navy-950/80 rounded-xl border border-slate-800 text-xs space-y-2">
                <span className="text-slate-400 block text-[10px] uppercase">
                  Emergency Contacts ({data.emergencyContacts.length})
                </span>
                <div className="space-y-2">
                  {data.emergencyContacts.map((c: any, i: number) => (
                    <div key={i} className="flex items-center justify-between text-slate-200">
                      <div>
                        <span className="font-semibold text-white">{c.name}</span>
                        <span className="text-slate-400 text-[11px] ml-1.5">({c.relationship})</span>
                      </div>
                      <a
                        href={`tel:${c.phoneNumber}`}
                        className="flex items-center gap-1.5 px-3 py-1 bg-teal-500/10 text-teal-300 border border-teal-500/30 rounded-lg font-mono text-xs hover:bg-teal-500/20 transition-colors"
                      >
                        <Phone className="w-3 h-3" />
                        <span>{c.phoneNumber}</span>
                      </a>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>

          <div className="pt-4 border-t border-slate-800 flex items-center justify-between text-[11px] text-slate-500">
            <span className="flex items-center gap-1">
              <Shield className="w-3.5 h-3.5 text-teal-400" />
              Verified Patient Allow-List
            </span>
            <span>MediChain-AI Vault</span>
          </div>
        </div>
      </div>
    </div>
  );
};
